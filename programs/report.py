#!/usr/bin/env python3
"""Run every protocol test (programs/*/test_*.py) and write programs/README.md: one row per
protocol with its programs, their size and the test outcome. What a row says the tests check is
the test module's docstring, so the table cannot claim more than the tests do.

    python3 programs/report.py      # writes README.md; exit status 1 if a test fails
"""
import importlib.util
import io
import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "sim" / "model"))
from asm import assemble          # noqa: E402

rows, failed = [], False
for path in sorted(HERE.glob("*/test_*.py")):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    result = unittest.TextTestRunner(stream=io.StringIO()).run(
        unittest.defaultTestLoader.loadTestsFromModule(module))
    passed = result.testsRun - len(result.failures) - len(result.errors)
    failed |= passed != result.testsRun
    programs = ", ".join(f"`{p.name}` ({len(assemble(p.read_text()))})" for p in sorted(path.parent.glob("*.asm")))
    checks = " ".join((module.__doc__ or "").split())
    rows.append(f"| {path.parent.name} | {programs or 'programs of other rows'} | "
                f"{passed} / {result.testsRun} | {checks} |")

(HERE / "README.md").write_text(f"""# Protocol programs

Generated by `programs/report.py` from the test results: do not edit by hand.

Every program runs on the chip model (`sim/model/chip.py`) and is judged on the pins by reference
devices written from the protocol specifications (`test/shared/devices.py`), independent of the
emulator. Program size in instructions (of 64).

| Protocol | Programs | Tests passed | What the tests check |
|---|---|---|---|
""" + "\n".join(rows) + "\n")
print("\n".join(rows))
sys.exit(1 if failed else 0)
